#include "mq135.h"
#include <math.h>   // Para pow()

// ?????????????????????????????????????????????????????
// PASO 1: Inicializar ADC para canal AN1
// Igual que el LM35 pero en canal 1 (AN1 = RA1)
// ?????????????????????????????????????????????????????
void MQ135_Init(void) {
    // RA1 como entrada analógica
    TRISAbits.TRISA1 = 1;

    // ADCON1: AN0 y AN1 analógicos, resto digital
    // 0x0D = 0b00001101 ? 2 pines analógicos (AN0 y AN1)
    // Vref+ = VDD (5V), Vref- = GND
    ADCON1 = 0x0D;

    // ADCON2: igual que LM35 ? justificado derecha, FOSC/64, 20TAD
    ADCON2 = 0xBE;

    // ADCON0: canal AN1 seleccionado (CHS=0001), ADC ON
    // 0x05 = 0b00000101 ? CHS=0001 (AN1), ADON=1
    ADCON0 = 0x05;

    __delay_ms(100);  // Estabilización ADC

    __delay_ms(3000);
}

float MQ135_LeerADC(void) {
    unsigned long suma = 0;
    unsigned char i;

    // Asegurar que el canal es AN1
    ADCON0 = 0x05;
    __delay_us(25);  // Tiempo de adquisición

    for(i = 0; i < MQ_MUESTRAS; i++) {
        ADCON0bits.GO_nDONE = 1;
        while(ADCON0bits.GO_nDONE);
        suma += (unsigned int)(((unsigned int)ADRESH << 8) | ADRESL);
        __delay_ms(5);
    }

    return (float)(suma / MQ_MUESTRAS);
}

// ?????????????????????????????????????????????????????
// PASO 3: ADC ? Voltaje ? Rs
//
// Voltaje en AOUT:
//   Vout = adc * (5000mV / 1024)
//
// Rs usando divisor de voltaje:
//   Rs = RL * (Vcc - Vout) / Vout
//   Rs = RL * (5000 - Vout) / Vout
//
// Resultado en k?
// ?????????????????????????????????????????????????????
float MQ135_calcularRs(float adc) {
    float voltaje;  // en mV
    float rs;       // en k?

    // Convertir ADC a voltaje
    voltaje = adc * (5000.0 / 1024.0);

    // Evitar division por cero
    if(voltaje <= 0.0) voltaje = 0.001;

    // Calcular Rs
    rs = RL_VALUE * (5000.0 - voltaje) / voltaje;

    return rs;
}

// ?????????????????????????????????????????????????????
// PASO 4: Rs/R0 ? PPM
//
// La curva del datasheet es logarítmica:
//   ppm = A * (Rs/R0)^B
//
// Para CO2 aproximado según datasheet MQ-135:
//   A = 116.60, B = -2.769
//
// Ejemplo: Rs/R0 = 1.0 ? ppm ? 116 (aire normal ~400ppm CO2)
// ?????????????????????????????????????????????????????
float MQ135_calcularPPM(float rs, float r0) {
    float ratio;
    float ppm;

    if(r0 <= 0.0) r0 = R0_DEFAULT;  // Protección

    ratio = rs / r0;

    if(ratio <= 0.0) ratio = 0.001; // Protección

    // Curva datasheet: ppm = A * ratio^B
    ppm = CURVE_A * pow(ratio, CURVE_B);

    // Limitar rango válido del sensor (10 a 10000 ppm)
    if(ppm < 10.0)    ppm = 10.0;
    if(ppm > 10000.0) ppm = 10000.0;

    return ppm;
}

// ?????????????????????????????????????????????????????
// CALIBRACIÓN: Calcular R0 en aire limpio
//
// Coloca el sensor en aire limpio (afuera o ventilado)
// y llama esta función ? devuelve el valor R0 real
//
// Según datasheet: en aire limpio Rs/R0 = 3.6
// Por lo tanto: R0 = Rs / 3.6
// ?????????????????????????????????????????????????????
float MQ135_calibrarR0(void) {
    float adc, rs, r0;
    unsigned char i;
    float suma = 0.0;

    // 50 lecturas para calibración precisa
    for(i = 0; i < 50; i++) {
        adc = MQ135_LeerADC();
        rs  = MQ135_calcularRs(adc);
        suma += rs;
        __delay_ms(100);
    }

    rs = suma / 50.0;

    // En aire limpio Rs/R0 = 3.6 (datasheet MQ-135)
    r0 = rs / 3.6;

    return r0;  // Guarda este valor en R0_DEFAULT
}
