// ── Primitivas I2C para OLED ────────────────────────────────
void OLED_Command(unsigned char cmd) {
    I2C_Start();
    I2C_Write(OLED_ADDR);
    I2C_Write(0x00);   // byte de control = comando
    I2C_Write(cmd);
    I2C_Stop();
}

void OLED_Data(unsigned char data) {
    I2C_Start();
    I2C_Write(OLED_ADDR);
    I2C_Write(0x40);   // byte de control = datos
    I2C_Write(data);
    I2C_Stop();
}

// ── Init identica al codigo que funciono ───────────────────
void OLED_Init(void) {
    __delay_ms(200);
    OLED_Command(0xAE); // display OFF
    OLED_Command(0xD5); OLED_Command(0xF0); // clock
    OLED_Command(0xA8); OLED_Command(0x3F); // multiplex 64
    OLED_Command(0xD3); OLED_Command(0x00); // offset 0
    OLED_Command(0x40);                     // start line 0
    OLED_Command(0x8D); OLED_Command(0x14); // charge pump ON
    OLED_Command(0x20); OLED_Command(0x00); // horizontal addressing
    OLED_Command(0xA1);                     // segment remap
    OLED_Command(0xC8);                     // COM scan direction
    OLED_Command(0xDA); OLED_Command(0x12); // COM pins
    OLED_Command(0x81); OLED_Command(0xFF); // contrast maximo
    OLED_Command(0xD9); OLED_Command(0xF1); // pre-charge
    OLED_Command(0xDB); OLED_Command(0x40); // VCOMH
    OLED_Command(0xA4);                     // display RAM
    OLED_Command(0xA6);                     // normal (no invertido)
    OLED_Command(0xAF); // display ON
    __delay_ms(100);
}

// ── Limpiar pantalla completa ───────────────────────────────
void OLED_Clear(void) {
    unsigned int i;
    OLED_Command(0x21); OLED_Command(0); OLED_Command(127); // col 0-127
    OLED_Command(0x22); OLED_Command(0); OLED_Command(7);   // pag 0-7
    for (i = 0; i < 1024; i++) OLED_Data(0x00);
}

// ── Limpiar solo una linea (rapido) ────────────────────────
void OLED_ClearLine(unsigned char linea) {
    unsigned char i;
    OLED_SetCursor(0, linea);
    for (i = 0; i < 128; i++) OLED_Data(0x00);
}

// ── Posicionar cursor ───────────────────────────────────────
void OLED_SetCursor(unsigned char col, unsigned char page) {
    OLED_Command(0xB0 + page);
    OLED_Command(0x00 | (col & 0x0F));
    OLED_Command(0x10 | (col >> 4));
}

// ── Escribir un caracter ────────────────────────────────────
void OLED_WriteChar(char c) {
    unsigned char i;
    int index = 0;
    if      (c == ' ')             index = 0;
    else if (c >= '0' && c <= '9') index = c - '0' + 1;
    else if (c >= 'A' && c <= 'Z') index = c - 'A' + 11;
    else if (c == ':')             index = 37;
    else if (c == '%')             index = 38;
    else if (c == '.')             index = 39;
    for (i = 0; i < 5; i++) OLED_Data(font5x7[index][i]);
    OLED_Data(0x00); // separacion
}

// ── Escribir string ─────────────────────────────────────────
void OLED_WriteString(char *str) {
    while (*str) {
        OLED_WriteChar(*str);
        str++;
    }
}
